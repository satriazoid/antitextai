"""Comment spam in source code: measure it, then scrub it.

The core cleaner deletes narration lines it can recognize. It cannot judge
a wall of prose comments, forty lines explaining a ten-line function, or a
file that is mostly comments with some code in between. This module measures
that shape per language and removes long comment blocks. Blocks carrying a
license, a tool directive, or a task marker are never touched, and neither
are docstrings: a docstring can hold a contract, so it is reported, not cut.
"""
from __future__ import annotations

import ast
import re
from dataclasses import dataclass
from typing import Iterable, Optional

HASH_EXTS = frozenset({
    ".py", ".rb", ".sh", ".bash", ".zsh", ".ps1", ".psm1", ".yaml", ".yml",
    ".toml", ".r", ".pl", ".pm", ".tf", ".hcl", ".ex", ".exs", ".erl",
})
SLASH_EXTS = frozenset({
    ".js", ".mjs", ".cjs", ".jsx", ".ts", ".tsx", ".java", ".c", ".h", ".cc",
    ".cpp", ".hpp", ".cs", ".go", ".rs", ".swift", ".kt", ".kts", ".scala",
    ".css", ".scss", ".less", ".proto", ".graphql",
})
CODE_EXTENSIONS = HASH_EXTS | SLASH_EXTS | frozenset({".php", ".sql", ".lua", ".hs"})

LONG_BLOCK = 5
LONG_LINE = 160
HEAVY_RATIO = 0.5
HEAVY_MIN = 10
DOCSTRING_SPAM = 8
MODULE_DOCSTRING_SPAM = 16

KEEP_TEXT = re.compile(
    r"(?i)copyright|license|licensed|spdx|permission is hereby|warranty|liability"
    r"|@author|@copyright")
KEEP_DIRECTIVE = re.compile(
    r"(?i)(?:#!|-\*-|coding[:=]|type:\s|noqa|pragma|pylint|fmt:|region"
    r"|eslint|tslint|@ts-|prettier-ignore|generated by|do not edit)")
KEEP_TASK = re.compile(r"\b(?:TODO|FIXME|XXX|HACK)\s*[:(\]]")


@dataclass
class CommentFinding:
    path: str
    line: int
    rule: str
    text: str
    suggestion: str = ""

    def to_dict(self) -> dict:
        return {
            "path": self.path,
            "line": self.line,
            "rule": self.rule,
            "text": self.text.strip(),
            "suggestion": self.suggestion,
        }


def _style(path: str):
    name = path.replace("\\", "/").rsplit("/", 1)[-1].lower()
    ext = "." + name.rsplit(".", 1)[-1] if "." in name else ""
    if ext in HASH_EXTS or name == "dockerfile":
        return ("#",), None
    if ext in SLASH_EXTS:
        return ("//",), "c"
    if ext == ".php":
        return ("//", "#"), "c"
    if ext in (".sql", ".lua", ".hs"):
        return ("--",), None
    if ext in (".html", ".htm", ".xml", ".svg", ".vue", ".svelte"):
        return (), "html"
    return (), None


def _docstring_spans(text: str) -> list:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    spans = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if not node.body or not isinstance(node.body[0], ast.Expr):
            continue
        if ast.get_docstring(node, clean=False) is not None:
            first = node.body[0]
            spans.append((first.lineno, first.end_lineno, isinstance(node, ast.Module)))
    return spans


def _analyze(path: str, text: str) -> dict:
    markers, block_kind = _style(path)
    lines = text.split("\n")
    kinds = []
    in_block = False
    for line in lines:
        stripped = line.strip()
        if in_block:
            kinds.append("comment")
            closer = "-->" if block_kind == "html" else "*/"
            if closer in line:
                in_block = False
            continue
        if not stripped:
            kinds.append("blank")
            continue
        opener = "<!--" if block_kind == "html" else "/*"
        closer = "-->" if block_kind == "html" else "*/"
        if block_kind and stripped.startswith(opener):
            kinds.append("comment")
            if closer not in stripped[len(opener):]:
                in_block = True
            continue
        if any(stripped.startswith(m) for m in markers):
            kinds.append("comment")
            continue
        kinds.append("code")
    spans = []
    if path.replace("\\", "/").rsplit(".", 1)[-1].lower() == "py":
        spans = _docstring_spans(text)
        for start, end, _is_module in spans:
            for i in range(start - 1, min(end, len(kinds))):
                kinds[i] = "docstring"
    blocks = []
    start = None
    for i, kind in enumerate(kinds):
        if kind == "comment" and start is None:
            start = i
        elif kind != "comment" and start is not None:
            blocks.append((start, i - 1))
            start = None
    if start is not None:
        blocks.append((start, len(kinds) - 1))
    counts = {k: kinds.count(k) for k in ("code", "comment", "blank", "docstring")}
    return {"lines": lines, "kinds": kinds, "blocks": blocks, "spans": spans, **counts}


def scan_text(path: str, text: str) -> list:
    info = _analyze(path, text)
    lines, kinds = info["lines"], info["kinds"]
    findings = []
    spoken = info["comment"] + info["docstring"]
    nonblank = spoken + info["code"]
    if spoken >= HEAVY_MIN and nonblank and spoken / nonblank >= HEAVY_RATIO:
        findings.append(CommentFinding(
            path=path, line=1, rule="COMMENT_HEAVY",
            text=f"{spoken} of {nonblank} non-blank lines are comments or docstrings",
            suggestion="scrub long blocks with clean-comments; real docs belong in a docs file",
        ))
    for start, end in info["blocks"]:
        size = end - start + 1
        if size >= LONG_BLOCK:
            findings.append(CommentFinding(
                path=path, line=start + 1, rule="LONG_COMMENT_BLOCK",
                text=lines[start].strip()[:80],
                suggestion=f"remove or shrink this {size}-line comment block",
            ))
        for i in range(start, end + 1):
            if len(lines[i].strip()) > LONG_LINE:
                findings.append(CommentFinding(
                    path=path, line=i + 1, rule="LONG_COMMENT_LINE",
                    text=lines[i].strip()[:80],
                    suggestion="a comment this long is documentation or narration; move it or delete it",
                ))
    for start, end, is_module in info["spans"]:
        size = end - start + 1
        limit = MODULE_DOCSTRING_SPAM if is_module else DOCSTRING_SPAM
        if size >= limit:
            findings.append(CommentFinding(
                path=path, line=start, rule="DOCSTRING_SPAM",
                text=f"{size}-line docstring",
                suggestion="strip docstrings on internal helpers; keep only contract facts",
            ))
    findings.sort(key=lambda f: (f.line, f.rule))
    return findings


def _line_kept(line: str) -> bool:
    return bool(KEEP_TEXT.search(line) or KEEP_DIRECTIVE.search(line)
                or KEEP_TASK.search(line))


def scrub_text(path: str, text: str, *, min_block: int = 4) -> str:
    crlf = "\r\n" in text
    if crlf:
        text = text.replace("\r\n", "\n")
    info = _analyze(path, text)
    lines, kinds = info["lines"], info["kinds"]
    drop = set()
    for start, end in info["blocks"]:
        segment = lines[start:end + 1]
        local = set()
        run = []
        for i, line in enumerate(segment):
            if _line_kept(line):
                if len(run) >= min_block:
                    local.update(run)
                run = []
            else:
                run.append(i)
        if len(run) >= min_block:
            local.update(run)
        if local and len(local) * 2 >= len(segment):
            local.update(i for i, line in enumerate(segment) if not _line_kept(line))
        drop.update(start + i for i in local)
    kept = [line for i, line in enumerate(lines) if i not in drop]
    out = []
    blanks = 0
    for line in kept:
        if line.strip():
            blanks = 0
            out.append(line)
        else:
            blanks += 1
            if blanks <= 2 and out:
                out.append(line)
    result = "\n".join(out).rstrip("\n") + ("\n" if out else "")
    return result.replace("\n", "\r\n") if crlf else result


def scan_paths(
    paths: Iterable[str],
    *,
    extensions: Optional[Iterable[str]] = None,
    exclude_dirs: Optional[Iterable[str]] = None,
    exclude_globs: Iterable[str] = (),
) -> list:
    from .files import iter_text_files

    kwargs: dict = {"exclude_globs": exclude_globs,
                    "extensions": CODE_EXTENSIONS if extensions is None else extensions}
    if exclude_dirs is not None:
        kwargs["exclude_dirs"] = exclude_dirs
    reports = []
    for path, text in iter_text_files(paths, **kwargs):
        findings = scan_text(str(path), text)
        if findings:
            info = _analyze(str(path), text)
            reports.append({
                "path": str(path),
                "findings": [f.to_dict() for f in findings],
                "count": len(findings),
                "code_lines": info["code"],
                "comment_lines": info["comment"] + info["docstring"],
            })
    return reports


def format_report(reports: list) -> str:
    out = []
    for r in reports:
        out.append(f"{r['path']}  ({r['comment_lines']} comment lines, {r['code_lines']} code lines)")
        for f in r["findings"]:
            out.append(
                f"    line {f['line']} [{f['rule']}]  {f['text']!r}"
                + (f"  -> {f['suggestion']}" if f.get("suggestion") else "")
            )
        out.append("")
    total = sum(r["count"] for r in reports)
    out.append(f"{len(reports)} file(s) with comment spam, {total} finding(s)")
    return "\n".join(out)
